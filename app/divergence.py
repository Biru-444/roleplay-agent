@dataclass
class DivergenceCheck:
    diverges: bool
    fact: str = ""
    raw: str = ""


def check_turn(player_message: str, reply: str, chapter: int) -> DivergenceCheck:
    """เรียก LLM รอบเล็กเพื่อสรุปว่าเทิร์นนี้เบี่ยงจากต้นฉบับไหม

    คืนค่า diverges=False เงียบๆ ถ้า LLM ล่ม ตอบว่าง หรือ parse JSON ไม่ได้ — ฟีเจอร์นี้เป็นของเสริม
    ไม่ควรทำให้ทั้งเทิร์นของผู้เล่นพังเพราะ call เสริมนี้ล้มเหลว (แนวทางเดียวกับที่
    rag.py ทำเวลาค้นคลังนิยายไม่สำเร็จ — ดูใน main.py เทียบ) และไม่ควรเก็บ fact ที่ parse
    ไม่แน่ใจลงเซฟ เพราะ divergence_log มีน้ำหนักเหนือเนื้อหาต้นฉบับในเทิร์นถัดๆ ไป
    ถ้าเก็บผิดจะพาเนื้อเรื่องหลุดต่อเนื่อง
    """
    user_message = (
        f"ตอนที่ {chapter} ของเนื้อเรื่องต้นฉบับ\n"
        f"ข้อความที่ผู้เล่นพิมพ์ (สิ่งที่ผู้เล่นพยายามให้เกิดขึ้น — ไม่ใช่เกณฑ์ตัดสิน): {player_message}\n"
        f"สิ่งที่เกิดขึ้นจริงในฉาก (เกณฑ์เดียวที่ใช้ตัดสินและเขียน fact): {reply}"
    )
    try:
        result = llm.generate_response(
            system_prompt=_SYSTEM_PROMPT,
            history=[],
            user_message=user_message,
            temperature=0.2,       # งานนี้ต้องการความคงเส้นคงวา ไม่ใช่ความสร้างสรรค์แบบบทสนทนาหลัก
            max_output_tokens=200,
            response_mime_type="application/json",
            response_schema=_DivergenceResult,
        )
    except Exception as e:
        print(f"[divergence][warn] ตรวจไม่สำเร็จ: {type(e).__name__}: {e}")
        return DivergenceCheck(diverges=False)

    text = (result.text or "").strip()
    if not text:
        return DivergenceCheck(diverges=False, raw=text)

    try:
        parsed = _DivergenceResult.model_validate_json(text)
    except Exception as e:
        # response_schema ควรบังคับให้ parse ผ่านเสมอ แต่ถ้า SDK/โมเดลพลาดจนได้ JSON เพี้ยน
        # ให้ล้มเหลวแบบปลอดภัย (ไม่เก็บ fact ที่ไม่มั่นใจ) ดีกว่าเดาแล้วเก็บขยะลงเซฟ
        print(f"[divergence][warn] parse JSON ไม่สำเร็จ: {e} — raw={text!r}")
        return DivergenceCheck(diverges=False, raw=text)

    if not parsed.diverges or not parsed.fact.strip():
        return DivergenceCheck(diverges=False, raw=text)
    return DivergenceCheck(diverges=True, fact=parsed.fact.strip(), raw=text)
