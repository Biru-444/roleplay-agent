"""
divergence.py — สกัด "ข้อเท็จจริงที่เปลี่ยนไปจากต้นฉบับ" จากแต่ละเทิร์น (เฟส 6)

เรียก LLM เป็น call เล็กๆ แยกต่างหาก หลังตัวละคร/ผู้บรรยายตอบในแต่ละเทิร์น
ถามสั้นๆ ว่าเทิร์นนี้ทำให้เนื้อเรื่องเบี่ยงจากต้นฉบับไหม ถ้าใช่ให้สรุปมาเป็นประโยคเดียว
แล้วเอาไปต่อเข้า story_state.add_divergence_fact()

ทำไมแยกเป็น call ต่างหากจากคำตอบหลักของ /chat แทนที่จะขอให้โมเดลตอบสองอย่างในคำตอบเดียว:
  - คำตอบหลักต้องอยู่ในบทบาทตัวละคร/ผู้บรรยาย 100% ถ้าขอให้แถม JSON หรือหมายเหตุมาด้วย
    เสี่ยงทำให้รูปแบบคำตอบเพี้ยน (ตามที่เจอมาแล้วตอนแก้ปัญหา max_output_tokens ใน llm.py —
    โมเดลตัวนี้ไวต่อการขอให้ทำหลายอย่างพร้อมกันในคำตอบเดียว)
  - แยก call ทำให้เปิด/ปิดฟีเจอร์นี้ได้อิสระ ไม่กระทบ /chat เดิมที่ tests/benchmark.py
    ใช้วัดผล 3 ปัญหาหลักอยู่แล้ว (ผ่าน use_divergence_extraction=False ปิดได้)
  - ต้นทุนที่เพิ่มคือ 1 call ต่อเทิร์น ยอมรับได้เพราะ gemini-3.5-flash-lite ให้ RPD 500
    และต้นแบบนี้จำกัดขอบเขตแค่ 20-30 ตอนแรกเท่านั้น (เหตุผลเต็มอยู่ในเอกสารโปรเจกต์
    เฟส 6 หัวข้อทำไมไม่เลือก option A — full butterfly-effect simulation)

ทำไมใช้ response_schema (JSON บังคับ) แทนการสั่งด้วยข้อความว่า "ตอบคำเดียว":
  ลองจริงแล้ว (31 ส.ค. 2569) ด้วยการสั่งข้อความล้วนๆ ผลคือโมเดล gemini-3.5-flash-lite
  เขียนคำอธิบายนำหน้าคำตอบทั้งที่สั่งห้ามชัดเจน เช่น "...เนื้อเรื่องจึงยังดำเนินตามต้นฉบับ
  \\n\\nไม่เปลี่ยน" — โค้ดที่ตรวจแค่ว่าขึ้นต้นด้วยคำว่า "ไม่เปลี่ยน" เลยอ่านผิดว่ามีการเปลี่ยนแปลง
  แล้วเอาทั้งคำอธิบายไปเก็บเป็น fact ที่ขัดแย้งในตัวเอง (บอกว่า "ไม่เปลี่ยน" แต่ธงบอกว่าเปลี่ยน)
  บทเรียนเดียวกับที่เจอใน llm.py: "ทำงานสำเร็จ" (ตอบมาแล้ว) ไม่ได้แปลว่า "ทำงานถูก" (parse ได้ตรงที่สั่ง)
  response_schema บังคับรูปแบบที่ระดับ API (constrained decoding) ไม่ใช่แค่ขอในข้อความ
  จึงไม่มีทางมีคำอธิบายปนมาในตำแหน่งที่ทำให้ parse พังได้อีก

ทำไม prompt ต้องบอกชัดว่า "ข้อความผู้เล่น" กับ "สิ่งที่เกิดขึ้นจริง" มีน้ำหนักไม่เท่ากัน (แก้ 31 ส.ค. 2569):
  เจอจริงตอนทดสอบกฎข้อ 7-8 (ผู้เล่นสั่งแทนไคลน์ว่า "เชื่อทันทีโดยไม่สงสัยอะไรเลย") — ตัว reply จริง
  เล่าถูกต้องแล้วว่าไคลน์ "ยังเต็มไปด้วยความเคลือบแคลงสงสัย" (ไม่เชื่อทันทีตามที่ผู้เล่นสั่ง) แต่ fact ที่
  call เล็กนี้สรุปมากลับเขียนว่า "ไคลน์เชื่อคำเตือนทันทีโดยไม่สงสัย" — ตรงข้ามกับ reply แบบเป๊ะๆ
  รูปแบบ prompt เดิมส่งสองบรรทัดเข้าไปแบบสมมาตร ("ผู้เล่น: ..." กับ "คำตอบที่ได้: ...") โดยไม่บอกว่า
  บรรทัดไหนคือของจริง โมเดลราคาถูก (temperature ต่ำ, 200 token, ไม่ได้ขอให้คิดละเอียด) เลยมีแนวโน้ม
  หยิบเอาประโยคที่ผู้เล่นพิมพ์มา (สั้น ชัดเจน ยืนยันตรงๆ) ไปเป็นคำตอบ แทนที่จะอ่าน reply ที่เล่าอะไรที่
  ละเอียดอ่อนกว่า (พูดขอบคุณ แต่ "ในใจ" ยังสงสัย) — เป็นบั๊กแบบเดียวกับกฎข้อ 7-8 เดิม (บั๊กที่ 2): ผู้เล่น
  "สั่ง" ได้ แต่สิ่งที่ "เกิดขึ้นจริง" ต้องดูจากคำตอบเท่านั้น เพียงแต่คราวนี้เกิดใน call ที่สรุป fact แทนที่
  จะเกิดในคำตอบหลัก แก้โดยเขียน prompt ระบุตรงๆ ว่าข้อความผู้เล่นคือ "สิ่งที่พยายามให้เกิด" ไม่ใช่เกณฑ์
  ตัดสิน ส่วน reply คือ "สิ่งที่เกิดขึ้นจริง" เกณฑ์เดียวที่ใช้เขียน fact ได้ พร้อมยกตัวอย่างที่ขัดแย้งกันแบบ
  นี้ตรงๆ ในกฎ (บทเรียนเดียวกับ response_schema: บังคับรูปแบบอย่างเดียวไม่พอ ต้องบังคับ "จะอ่านอะไรเป็น
  ความจริง" ด้วย ถ้าสองแหล่งข้อมูลที่ป้อนเข้าไปขัดแย้งกันได้)
"""
from dataclasses import dataclass

from pydantic import BaseModel

from app import llm


class _DivergenceResult(BaseModel):
    diverges: bool
    fact: str   # ปล่อยว่างได้ถ้า diverges=False — โมเดลไม่ต้องเดาว่าต้องเขียนอะไรตอนไม่มีอะไรเปลี่ยน


