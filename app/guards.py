def get_stop_sequences(player_name: str) -> List[str]:
    """หยุดโมเดลตั้งแต่ระดับ API ก่อนที่มันจะเริ่มเขียนบทของผู้เล่น"""
    seqs = ["ผู้เล่น:", "Player:"]
    if player_name:
        seqs = [f"{player_name}:", f"\n{player_name} "] + seqs
    return seqs


